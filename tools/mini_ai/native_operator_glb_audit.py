"""Audits four REAL original GLBs from an AssetWright-owned learned plan.

All files must be generated by native MiniGeometry with proven source SHA.
Measures actual connected hull topology and specific morphological effects;
neither a CAD teacher nor a visual teacher is allowed to supply geometry.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from generated_glb_critic import inspect
from vehicle_design_critic import analyze
from native_socket_audit import compare,points_of

SCHEMA="assetwright-owned-native-planner-real-glb-evaluation-v1"
VARIANTS=("baseline","recess_rear_socket","sculpt_cockpit_shoulder","loft_rear_nacelle")

def audit(folder:Path)->dict:
    glbs={}
    for variant in VARIANTS:
        stem=f"native_planner__{variant}"
        meta=json.loads((folder/(stem+".json")).read_text())
        path=folder/(stem+".glb")
        if (meta.get("schema")!="assetwright-owned-native-planner-glb-v1" or
            meta.get("source_engine")!="android-native-MiniGeometry" or
            meta.get("original_procedural_asset") is not True or
            meta.get("variant")!=variant):
            raise ValueError("Untrusted model geometry source")
        raw=path.read_bytes()
        digest=hashlib.sha256(raw).hexdigest()
        if meta.get("source_glb_sha256")!=digest:
            raise ValueError("Native GLB checksum mismatch")
        model_sha=meta.get("model_sha256")
        if not isinstance(model_sha,str) or len(model_sha)!=64:
            raise ValueError("Missing owned planner provenance")
        if glbs and model_sha!=next(iter(glbs.values()))["model_sha"]:
            raise ValueError("Mixed models in a single experiment")
        level=meta.get("strength")
        if type(level) not in (int,float) or not 0<=level<=1:
            raise ValueError("Unbounded or invalid learned strength")
        if variant!="baseline" and level<.45:
            raise ValueError("Insufficient experimental geometry effect")
        mesh=inspect(path);style=analyze(path)
        if mesh["model_sha256"]!=digest or style["model_sha256"]!=digest:
            raise ValueError("Critic/GLB hash disagreement")
        glbs[variant]={"mesh":mesh,"design":style,"meta":meta,
                       "model_sha":model_sha,"source_sha":digest,"path":path}
    if len({x["source_sha"] for x in glbs.values()})!=4:
        raise ValueError("All four variants must contain different native geometry")
    base=glbs["baseline"]
    socket=glbs["recess_rear_socket"]
    shoulder=glbs["sculpt_cockpit_shoulder"]
    nacelle=glbs["loft_rear_nacelle"]
    socket_result=compare(base["mesh"],socket["mesh"],
                          points_of(base["path"]),points_of(socket["path"]))
    before=base["design"]["metrics"]
    sculpt=shoulder["design"]["metrics"]
    engine=nacelle["design"]["metrics"]
    shoulder_diff=round(sculpt["body_cockpit_shoulder_span"]-
                        before["body_cockpit_shoulder_span"],5)
    checks={
        "verified_original_and_disjoint_GLBS":True,
        "connected_recess_in_original_hull":socket_result["passed"],
        "cockpit_shoulder_broader_at_measured_upper_hull":shoulder_diff>=.01,
        "cockpit_shoulder_new_native_loft_vertices":
            next(p["triangles"] for p in shoulder["mesh"]["parts"]
                 if p["name"]=="Sculpted continuous body") >
            next(p["triangles"] for p in base["mesh"]["parts"]
                 if p["name"]=="Sculpted continuous body"),
        "nacelle_more_than_four_axial_sections":
            engine["engine_housing_axial_sections"]>=5,
        "nacelle_actual_fairing_flare":
            engine["engine_housing_flare_ratio"]>=1.25,
        "no_added_mesh_parts":all(x["mesh"]["mesh_parts"]==base["mesh"]["mesh_parts"]
                                  for x in glbs.values()),
        "no_invalid_faces":all(x["mesh"]["invalid_triangles"]==0
                               for x in glbs.values()),
        "no_nonmanifold_edges":all(x["mesh"]["nonmanifold_edges"]==0
                                   for x in glbs.values()),
        "no_new_inverted_closed_meshes":all(
            x["mesh"]["inverted_closed_parts"]<=base["mesh"]["inverted_closed_parts"]
            for x in glbs.values()),
        "mobile_triangle_budgets":all(0<x["mesh"]["triangles"]<=12000
                                      for x in glbs.values())
    }
    return {"schema":SCHEMA,"passed":all(checks.values()),
            "checks":checks,"research_checkpoint_sha256":base["model_sha"],
            "exact_glb_sha256":{k:v["source_sha"] for k,v in glbs.items()},
            "learned_strengths":{k:v["meta"]["strength"] for k,v in glbs.items()
                                 if k!="baseline"},
            "measured_cockpit_shoulder_gain_m":shoulder_diff,
            "measured_nacelle_flare_ratio":engine["engine_housing_flare_ratio"],
            "measured_nacelle_axial_sections":engine["engine_housing_axial_sections"],
            "measured_socket":socket_result,
            "triangle_counts":{k:v["mesh"]["triangles"] for k,v in glbs.items()},
            "limitations":"Verifies actual native mesh morphology and topology; no expert aesthetic evaluation, no automatic Android promotion, no general-purpose CAD synthesis."}

def run(source:Path,out:Path)->dict:
    report=audit(source)
    out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps({k:v for k,v in report.items()
                      if k not in ("measured_socket","exact_glb_sha256")},indent=2))
    if not report["passed"]: raise SystemExit(2)
    return report

if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source",type=Path,required=True)
    p.add_argument("--out",type=Path,required=True)
    a=p.parse_args()
    run(a.source,a.out)
