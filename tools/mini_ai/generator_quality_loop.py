"""Score real original Android-generated GLBs, compare controlled variants.

The loop does NOT claim a beauty metric and does NOT retrain using its own
candidate scores as ground truth. It only screens actual exported geometry
and chooses a non-regressing structural benchmark for later visual review.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re

from generated_glb_critic import inspect, evaluate
from vehicle_design_critic import analyze as assess_design

SCHEMA="assetwright-generator-quality-loop-v1"
STEM=re.compile(r"^[a-z0-9_]+__(baseline|roof_plus|nose_sculpt|wider_haunch|sculpted_canopy|faired_mounts|integrated_aero|cockpit_bridge|rear_nacelle|architectural)$")
MAX_CASES=12
MAX_VARIANTS=60
MIN_DELTA=.005


def run(folder:Path,out:Path)->dict:
    targets=sorted(folder.glob("*.json"))
    if not 1<=len(targets)<=MAX_VARIANTS:
        raise ValueError("Unexpected exported benchmark size")
    seen=set()
    groups={}
    outcomes=[]
    for path in targets:
        if not STEM.fullmatch(path.stem):
            raise ValueError("Unexpected benchmark fixture name")
        target=json.loads(path.read_text(encoding="utf-8"))
        if target.get("expected_engine")!="android-native-MiniGeometry":
            raise ValueError("Not generated by Assetwright's native geometry engine")
        case,variant=target.get("case"),target.get("variant")
        if not isinstance(case,str) or path.stem!=case+"__"+variant:
            raise ValueError("Target/filename mismatch")
        key=(case,variant)
        if key in seen:raise ValueError("Duplicate generated candidate")
        seen.add(key)
        glb=path.with_suffix(".glb")
        if not glb.is_file():
            raise ValueError("Missing real generated GLB for "+path.stem)
        actual=hashlib.sha256(glb.read_bytes()).hexdigest()
        if target.get("source_glb_sha256")!=actual:
            raise ValueError("Generated GLB checksum does not match target")
        audit=inspect(glb)
        score=evaluate(audit,target)
        design=assess_design(glb)
        if design["model_sha256"]!=actual:
            raise ValueError("Visual proxy/audit SHA disagreement")
        row={
            "case":case,"variant":variant,"file":glb.name,
            "source_sha256":actual,
            "score":score["score"],"passed":score["passed"],
            "design_proxy_score":design["proxy_quality_score"],
            "design_proxy_checks":design["checks"],
            "design_proxy_metrics":design["metrics"],
            "checks":score["checks"],"measurements":score["measurements"],
            "invalid_triangles":audit["invalid_triangles"],
            "nonmanifold_edges":audit["nonmanifold_edges"]
        }
        outcomes.append(row)
        groups.setdefault(case,[]).append(row)
    if len(groups)>MAX_CASES:
        raise ValueError("Too many benchmark cases")
    summaries=[]
    for case,rows in sorted(groups.items()):
        baselines=[r for r in rows if r["variant"]=="baseline"]
        if len(baselines)!=1:
            raise ValueError("Every controlled case requires exactly one baseline")
        baseline=baselines[0]
        # A quantitative height increase alone no longer wins: the new
        # design candidate must improve at least one specific shape proxy.
        valid=sorted((r for r in rows if r["passed"]),
                     key=lambda x:(-x["design_proxy_score"],-x["score"],x["variant"]))
        best=valid[0] if valid else None
        if not baseline["passed"]:
            # No procedural parameter edits can self-approve a broken
            # incumbent. Require external code review before promotion.
            decision="baseline_failed_manual_review"
            selected=None
        elif (best and best["variant"]!="baseline" and
              best["design_proxy_score"]>=baseline["design_proxy_score"]+.25 and
              best["score"]>=baseline["score"]-.05):
            selected=best
            decision="candidate_for_human_visual_review"
        else:
            selected=baseline
            decision="retain_baseline"
        summaries.append({
            "case":case,"decision":decision,
            "baseline_score":baseline["score"],
            "baseline_design_proxy_score":baseline["design_proxy_score"],
            "selected_design_proxy_score":selected["design_proxy_score"] if selected else None,
            "selected_variant":selected["variant"] if selected else None,
            "selected_glb":selected["file"] if selected else None,
            "selected_sha256":selected["source_sha256"] if selected else None,
            "structurally_passing_candidates":len(valid),
            "total_candidates":len(rows)
        })
    return {
        "schema":SCHEMA,
        "source":"Native MiniGeometry + GlbWriter in Android JVM unit tests",
        "total_generated_glbs":len(outcomes),
        "cases":len(groups),
        "structurally_valid":sum(r["passed"] for r in outcomes),
        "structurally_invalid":sum(not r["passed"] for r in outcomes),
        "promoted_to_training":0,
        "android_model_updated":False,
        "private_assets_uploaded":False,
        "benchmark_critic_limits":"Measures structural safety plus narrow canopy-width and arm-section shape proxies. Not true aesthetic judgment, actual part integration, originality, rights or mechanical quality.",
        "results":summaries,
        "candidates":outcomes
    }


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source",type=Path,required=True)
    parser.add_argument("--out",type=Path,required=True)
    x=parser.parse_args()
    result=run(x.source,x.out)
    x.out.parent.mkdir(parents=True,exist_ok=True)
    x.out.write_text(json.dumps(result,indent=2)+"\n",encoding="utf-8")
    print(json.dumps({k:v for k,v in result.items() if k!="candidates"},indent=2))
    if result["structurally_invalid"]==result["total_generated_glbs"]:
        raise SystemExit("No usable structural candidates")

if __name__=="__main__":
    main()
