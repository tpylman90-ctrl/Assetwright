"""Diagnostic-only visual comparison of original Kotlin through-bore interfaces.

No geometry is generated by this renderer. Never substitute images for
the independent topology, forward-geometry or human visual approval gates.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from render_native_rocker_v2 import load_meshes, render

TRAIN=("train__if02__s21","train__if09__s17")
HELDOUT=("validation__if01__s12","validation__if03__s04",
         "aspect_shift__if02__s10","aspect_shift__if04__s08")
VIEWS=("front","rear","side","front_three_quarter")

def run(source:Path,reconstruction:Path,out:Path):
    out.mkdir(parents=True,exist_ok=True)
    manifest=[]
    for stem in (*TRAIN,*HELDOUT):
        for role in (("target",) if stem in TRAIN else ("target","student")):
            file=(source if role=="target" else reconstruction)/(stem+".glb")
            meshes,sha=load_meshes(file)
            if role=="target":
                metadata=json.loads(file.with_suffix(".json").read_text())
                if metadata["source_glb_sha256"]!=sha:
                    raise ValueError("Unverified original geometry preview")
            elif file.with_suffix(".sha256").read_text().strip()!=sha:
                raise ValueError("Unverified Kotlin student forward geometry")
            for view in VIEWS:
                for mode in ("clay","wire"):
                    output=out/(stem+"__"+role+"__"+view+"__"+mode+".png")
                    render(meshes,view,mode,
                           stem+" | "+role+" | "+view+" | "+mode,output)
                    manifest.append({
                        "source":stem,"role":role,"view":view,"mode":mode,
                        "glb_sha256":sha,"png":output.name,
                        "png_sha256":hashlib.sha256(output.read_bytes()).hexdigest()
                    })
    if len(manifest)!=80:
        raise ValueError("Missing source-hashed interface clay/wire views")
    result={"schema":"assetwright-native-interface-visual-review-v1",
            "render_count":len(manifest),
            "status":"human_review_required",
            "limitations":"Orthographic diagnostic views, not a finished game-ready asset",
            "renders":manifest}
    (out/"review_manifest.json").write_text(json.dumps(result,indent=2)+"\n")
    print(f"Verified {len(manifest)} original and student interface previews")
    return result

if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source",required=True,type=Path)
    p.add_argument("--reconstructed",required=True,type=Path)
    p.add_argument("--out",required=True,type=Path)
    a=p.parse_args()
    run(a.source,a.reconstructed,a.out)
